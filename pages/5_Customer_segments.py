import matplotlib.pyplot as plt
import pandas as pd
import streamlit as st
from sklearn.cluster import KMeans
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import ConfusionMatrixDisplay, accuracy_score, silhouette_score
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

st.title("Customer segments (no target variable)")
st.caption("Synthetic data generated by 19_make_customers.py. Real customers are less cleanly separated.")

@st.cache_data
def load():
    customers = pd.read_csv("customers.csv")
    return customers, StandardScaler().fit_transform(customers)

@st.cache_data
def k_scores():
    _, X_scaled = load()
    rows = []
    for k in range(2, 9):
        km = KMeans(n_clusters=k, random_state=42, n_init=10).fit(X_scaled)
        rows.append({"k": k, "inertia": km.inertia_, "silhouette": silhouette_score(X_scaled, km.labels_)})
    return pd.DataFrame(rows)

@st.cache_resource
def segment_and_train(k):
    customers, X_scaled = load()
    segments = KMeans(n_clusters=k, random_state=42, n_init=10).fit_predict(X_scaled)
    X_train, X_test, y_train, y_test = train_test_split(
        customers, segments, test_size=0.2, random_state=42, stratify=segments
    )
    rf = RandomForestClassifier(n_estimators=200, random_state=42).fit(X_train, y_train)
    return segments, rf, X_test, y_test

customers, _ = load()

# --- Step 1: choose k ---
st.header("1. How many segments?")
scores = k_scores()
fig, axes = plt.subplots(1, 2, figsize=(12, 4))
axes[0].plot(scores["k"], scores["inertia"], "o-")
axes[0].set_title("Elbow: inertia per k")
axes[1].plot(scores["k"], scores["silhouette"], "o-", color="orange")
axes[1].set_title("Silhouette per k")
st.pyplot(fig)

k = st.slider("Number of segments (k)", 2, 8, 4)
segments, rf, X_test, y_test = segment_and_train(k)

# --- Step 2: look at the segments ---
st.header("2. The segments")
fig, ax = plt.subplots()
ax.scatter(customers["income_k"], customers["spending_score"], c=segments, cmap="tab10", alpha=0.7)
ax.set_xlabel("Income (thousand per year)")
ax.set_ylabel("Spending score")
st.pyplot(fig)

profile = customers.assign(segment=segments).groupby("segment").mean().round(1)
profile["customers"] = pd.Series(segments).value_counts().sort_index()
st.dataframe(profile)

# --- Step 3: the segment becomes the target ---
st.header("3. A classifier trained on the segments")
pred = rf.predict(X_test)
st.metric("Accuracy on held-out customers", f"{accuracy_score(y_test, pred):.1%}")
fig, ax = plt.subplots()
ConfusionMatrixDisplay.from_predictions(y_test, pred, cmap="Greens", ax=ax)
st.pyplot(fig)
st.caption("High accuracy is expected: the segments were made from these same columns.")

# --- Step 4: try a new customer ---
st.header("4. Assign a new customer")
col1, col2 = st.columns(2)
income = col1.slider("Income (thousand per year)", 5, 120, 60)
spending = col1.slider("Spending score", 1, 100, 50)
age = col2.slider("Age", 18, 80, 40)
visits = col2.slider("Visits per month", 0.0, 16.0, 6.0)

new = pd.DataFrame([{"income_k": income, "spending_score": spending,
                     "age": age, "visits_per_month": visits}])[customers.columns]
st.subheader(f"→ Segment {rf.predict(new)[0]}")
proba = pd.Series(rf.predict_proba(new)[0], index=[f"Segment {s}" for s in rf.classes_])
st.bar_chart(proba)